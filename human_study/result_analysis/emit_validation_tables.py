"""Emit the human-validation LaTeX tables of the supplement from the survey CSVs.

The paper's main validation table (tables/human_validation_agreement.tex) is
maintained by hand, but the three appendix tables carry roughly a hundred
numbers between them and had drifted from the analysis outputs, so they are
rendered here instead, the way emit_identification_tables.py renders the
identification tables.

  human_validation_appendix.tex  per-rater agreement, weighted and unweighted,
                                 plus the reasonableness block
                                 <- agreement_by_model.csv, human_irr.csv
  human_npov_items.tex           the seven neutrality clauses by encyclopedia
                                 <- responses_tidy_anon.csv
  human_demographics.tex         participant descriptives
                                 <- demographics/*.csv, responses_tidy_anon.csv

Every input is the APPROVED-and-included frame of 140 ratings, so the tables
agree with the main paper's Table 2 by construction.

Usage: python emit_validation_tables.py [--out-dir DIR]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
from scipy import stats

HERE = Path(__file__).resolve().parent
ANALYSIS_DIR = HERE / "analyses_results" / "results-survey918273_analysis"
DEFAULT_OUT = HERE.parents[1] / "results" / "tables"

RATER_ROWS = [
    ("claude-opus-4-6", "Claude"),
    ("deepseek-v4-pro", "DeepSeek"),
    ("grok-4", "Grok"),
    ("mistralai", "Mistral"),
    ("llm_median", "Panel median"),
    ("shown_llm", "Rating shown"),
]
CRITERIA = {
    "viewpoints_fair_int": "Presents viewpoints fairly",
    "avoids_sides_int": "Avoids taking sides",
    "factual_language_int": "Uses fact-focused language",
    "facts_vs_opinions_int": "Distinguishes facts from opinion",
    "no_fringe_exaggeration_int": "Avoids exaggerating fringe views",
    "no_contested_as_fact_int": "Avoids contested claims as fact",
    "impartial_tone_int": "Maintains an impartial tone",
}
SOURCE_DISPLAY = {"wikipedia": "Wikipedia", "grokipedia_0.2": "Grokipedia"}
EDUCATION = {
    "Graduate degree (MA/MSc/MPhil/other)": "Graduate degree",
    "Undergraduate degree (BA/BSc/other)": "Undergraduate degree",
    "High school diploma/A-levels": "Secondary education",
    "Doctorate degree (PhD/other)": "Doctorate",
}
ETHNICITY_SHOWN = ["White", "Black", "Asian"]
FAMILIARITY = {"unknown": "Did not know of them", "heard_of": "Had heard of them",
               "knew": "Knew who they were"}


def _anon() -> pd.DataFrame:
    df = pd.read_csv(ANALYSIS_DIR / "responses_tidy_anon.csv", encoding="utf-8-sig")
    df["source_label"] = df["source"].map(SOURCE_DISPLAY).fillna(df["source"])
    return df


def _signed(x: float) -> str:
    return rf"$-{abs(x):.3f}$" if x < 0 else rf"$+{x:.3f}$"


def validation_appendix() -> str:
    agr = pd.read_csv(ANALYSIS_DIR / "agreement_by_model.csv").set_index("model")
    irr = pd.read_csv(ANALYSIS_DIR / "human_irr.csv").iloc[0]
    n_ratings = int(agr["n"].iloc[0])
    n_eff = float(agr["n_eff"].iloc[0])

    body = []
    for key, label in RATER_ROWS:
        r = agr.loc[key]
        shown = "--" if not r["n_shown"] > 0 else f"{int(r['n_shown'])}"
        reas = ["--" if not r["n_shown"] > 0 else f"{r[c]:.1f}" for c in
                ("reasonable_yes_pct", "reasonable_partial_pct",
                 "reasonable_no_pct", "reasonable_yes_pct_w")]
        body.append(
            f"    {label:<12} & {r['qwk']:.3f} [{r['qwk_lo']:.3f}, {r['qwk_hi']:.3f}]"
            f" & {r['exact_pct']:.1f} & {r['within1_pct']:.1f}"
            f" & {_signed(r['mean_signed_err'])}"
            f" & {r['qwk_w']:.3f} & {r['exact_pct_w']:.1f} & {r['within1_pct_w']:.1f}"
            f" & {shown} & " + " & ".join(reas) + r" \\"
        )
    body.insert(4, r"    \midrule")
    hh = (f"    Human--human & {irr['qwk_pairs']:.3f} "
          f"[{irr['qwk_pairs_lo']:.3f}, {irr['qwk_pairs_hi']:.3f}]"
          f" & {irr['exact_pct']:.1f} & {irr['within1_pct']:.1f}"
          + " & --" * 9 + r" \\")

    return "\n".join([
        r"% Human validation study -- full per-judge results (Appendix).",
        r"% Generated by survey/result_analysis/emit_validation_tables.py.",
        r"\begin{table*}[t]",
        r"  \centering",
        r"  \small",
        r"  \setlength{\tabcolsep}{3.5pt}",
        rf"  \caption{{Human validation study, full per-rater results ($n = {n_ratings}$ human",
        r"  ratings of 70 articles). \textit{Unweighted} columns describe the realised",
        r"  (disagreement-enriched) sample; \textit{weighted} columns post-stratify on the",
        r"  judge-disagreement bin to project onto the length-eligible paired corpus,",
        rf"  with $n_{{\text{{eff}}}} = {n_eff:.1f}$ the Kish effective sample size under those",
        r"  weights. $\hat{\kappa}$ is quadratically weighted Cohen's $\kappa$, whose",
        r"  confidence intervals are cluster bootstraps over articles",
        r"  (5{,}000 resamples). \textit{Exact} and $\pm1$ are exact and adjacent",
        r"  agreement, and $\overline{h-m}$ is the mean signed human-minus-judge",
        r"  difference. The \textit{reasonableness} block covers only the ratings each",
        r"  judge was actually shown for ($n_{\text{shown}}$), as every annotator saw one",
        r"  randomly assigned judge; \textit{Rating shown} pools all 140, and the last",
        r"  column is the post-stratified \textit{yes} share.}",
        r"  \label{tab:human_validation}",
        r"  \begin{tabular}{lcccrcccrrrrr}",
        r"    \toprule",
        r"    & \multicolumn{4}{c}{Unweighted} & \multicolumn{3}{c}{Weighted}",
        r"    & \multicolumn{5}{c}{Reasonableness of the shown rating (\%)} \\",
        r"    \cmidrule(lr){2-5}\cmidrule(lr){6-8}\cmidrule(lr){9-13}",
        r"    Rater & $\hat{\kappa}$ [95\% CI] & Exact & $\pm1$ & $\overline{h-m}$",
        r"          & $\hat{\kappa}$ & Exact & $\pm1$",
        r"          & $n_{\text{shown}}$ & Yes & Partially & No & Yes (w.) \\",
        r"    \midrule",
        *body,
        r"    \midrule",
        hh,
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table*}",
        "",
    ])


def npov_items() -> str:
    df = _anon()
    rows, wiki_all, grok_all = [], [], []
    for col, label in CRITERIA.items():
        cell = {}
        for src in ("Wikipedia", "Grokipedia"):
            v = df.loc[df["source_label"] == src, col]
            cell[src] = f"{v.mean():.2f} ({v.std():.2f})"
        art = df.groupby(["source_label", "taskid"])[col].mean()
        w, g = art["Wikipedia"].dropna(), art["Grokipedia"].dropna()
        p = stats.ttest_ind(w, g, equal_var=False).pvalue
        rows.append(f"    {label:<32} & {cell['Wikipedia']} & {cell['Grokipedia']} & {p:.3f} " + r"\\")
        wiki_all.append(w)
        grok_all.append(g)

    cols = list(CRITERIA)
    means = df.groupby("source_label")[cols].mean().mean(axis=1)
    art_mean = df.groupby(["source_label", "taskid"])[cols].mean().mean(axis=1)
    p_mean = stats.ttest_ind(art_mean["Wikipedia"], art_mean["Grokipedia"],
                             equal_var=False).pvalue
    n_ratings, n_articles = len(df), df["taskid"].nunique()
    per_source = int(n_articles / 2)

    return "\n".join([
        r"% Human ratings of the seven neutrality criteria, by source (Appendix).",
        r"% Generated by survey/result_analysis/emit_validation_tables.py.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{4pt}",
        r"  \caption{Human annotators' agreement with each clause of our neutrality",
        r"  definition, by encyclopedia. Items were rated from \textit{strongly disagree}",
        r"  ($-2$) to \textit{strongly agree} ($+2$), so a higher value means annotators",
        r"  judged the article to satisfy the criterion; standard deviations in",
        rf"  parentheses. Cells are means over the {n_ratings} ratings ({n_articles} articles, {per_source} per",
        rf"  source); $p$-values are two-sided Welch tests on the {n_articles} article-level means",
        r"  and are exploratory: the design is unpaired and not powered for a",
        r"  source contrast.}",
        r"  \label{tab:human_npov}",
        r"  \begin{tabular}{lccc}",
        r"    \toprule",
        r"    Neutrality criterion & Wikipedia & Grokipedia & $p$ \\",
        r"    \midrule",
        *rows,
        r"    \midrule",
        rf"    Mean over the seven criteria     & {means['Wikipedia']:.2f} & {means['Grokipedia']:.2f} & {p_mean:.3f} " + r"\\",
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])


def _mmss(seconds: float) -> str:
    return f"{int(seconds // 60)}:{int(round(seconds % 60)):02d}"


def demographics() -> str:
    cat = pd.read_csv(ANALYSIS_DIR / "demographics" / "summary_categorical.csv")
    num = pd.read_csv(ANALYSIS_DIR / "demographics" / "summary_numeric.csv").set_index("variable")
    df = _anon()
    n = len(df)

    def block(variable: str) -> pd.DataFrame:
        return cat[cat["variable"] == variable]

    sex = block("sex").set_index("level")["pct"]
    edu = block("education").set_index("level")["pct"]
    eth = block("ethnicity").set_index("level")["pct"]
    ctry = block("country_residence")
    top3, rest = ctry.iloc[:3], ctry.iloc[3:]

    pol = pd.cut(df["econ_leftright"].dropna(), bins=[0, 4, 6, 10],
                 labels=["Left (1--4)", "Centre (5--6)", "Right (7--10)"])
    pol_pct = pol.value_counts().reindex(pol.cat.categories) / n * 100
    n_optout = int(df["econ_leftright"].isna().sum())
    fam = df["knew_subject"].value_counts() / n * 100

    age, time = num.loc["age"], num.loc["time_taken_s"]
    rows = [
        r"    \multirow{2}{*}{Sex}",
        rf"      & Male & {sex['Male']:.1f} \\",
        rf"      & Female & {sex['Female']:.1f} \\",
        r"    \midrule",
        rf"    \multirow{{{len(edu)}}}{{*}}{{Highest education}}",
    ]
    rows += [rf"      & {EDUCATION.get(k, k)} & {v:.1f} \\" for k, v in edu.items()]
    other_eth = eth.drop(index=[e for e in ETHNICITY_SHOWN if e in eth.index]).sum()
    rows += [r"    \midrule", r"    \multirow{4}{*}{Ethnicity}"]
    rows += [rf"      & {e} & {eth[e]:.1f} \\" for e in ETHNICITY_SHOWN]
    rows += [rf"      & Mixed / other / undisclosed & {other_eth:.1f} \\",
             r"    \midrule", r"    \multirow{4}{*}{Country of residence}"]
    rows += [rf"      & {r.level} & {r.pct:.1f} \\" for r in top3.itertuples()]
    rest_pct = rest["n"].sum() / n * 100
    rows += [rf"      & {len(rest)} further countries & {rest_pct:.1f} \\",
             r"    \midrule", r"    \multirow{3}{*}{Political self-placement}"]
    rows += [rf"      & {k} & {v:.1f} \\" for k, v in pol_pct.items()]
    rows += [r"    \midrule", r"    \multirow{3}{*}{Familiarity with the subject}"]
    rows += [rf"      & {FAMILIARITY[k]} & {fam[k]:.1f} \\" for k in FAMILIARITY if k in fam]

    return "\n".join([
        r"% Participant descriptives for the human validation study (Appendix).",
        r"% Generated by survey/result_analysis/emit_validation_tables.py.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{4pt}",
        rf"  \caption{{Participants in the human validation study ($n = {n}$; each",
        r"  annotator rated exactly one article, so participant- and rating-level",
        r"  descriptives coincide). Demographics are the self-reported attributes held by",
        r"  Prolific; political self-placement was collected in the survey, on a 1",
        r"  (\textit{left}) to 10 (\textit{right}) scale, with an opt-out taken by "
        rf"{n_optout}",
        r"  participants.}",
        r"  \label{tab:human_demographics}",
        r"  \begin{tabular}{llr}",
        r"    \toprule",
        r"    Attribute & Level & \% \\",
        r"    \midrule",
        *rows,
        r"    \midrule",
        rf"    \multicolumn{{3}}{{l}}{{Age: mean {age['mean']:.1f} (SD {age['sd']:.1f}), "
        rf"median {age['median']:.0f}, range {age['min']:.0f}--{age['max']:.0f}}} \\",
        rf"    \multicolumn{{3}}{{l}}{{Completion time: median {_mmss(time['median'])}, "
        rf"mean {_mmss(time['mean'])} (SD {_mmss(time['sd'])})}} \\",
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in {
        "human_validation_appendix.tex": validation_appendix(),
        "human_npov_items.tex": npov_items(),
        "human_demographics.tex": demographics(),
    }.items():
        (args.out_dir / name).write_text(text)
        print(f"wrote {args.out_dir / name}")


if __name__ == "__main__":
    main()
